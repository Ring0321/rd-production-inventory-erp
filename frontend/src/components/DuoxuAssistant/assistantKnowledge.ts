export const answerAssistantKnowledge = (
  question: string,
  pages: readonly AssistantPage[]
): AssistantReply | undefined => {
  const entry = entries.find((item) => item.match.test(question))
  return entry
    ? {
        kind: 'LOCAL',
        title: entry.title,
        paragraphs: [...entry.paragraphs],
        source: '本地流程知识 · 现行作业规则',
        links: searchAssistantPages(entry.related, pages).slice(0, 3)
      }
    : undefined
}
