import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
import { createRequire } from 'node:module'
import { root, baseUrl, api, request, prepareFixture } from './RdQrLocalFixture.mjs'
const { fixture, tokens, accounts } = await prepareFixture()
const before = await api('/rd/putaway-task/location-map', tokens.warehouse)
assert.ok(before.length > 0, 'Requires existing isolated ERP location records')
const target = before.find(l=>l.enabled&&!l.frozen&&['EMPTY','PARTIAL'].includes(l.displayStatus)) || before[0]
const original = await api(`/rd/stock-lot/page?locationId=${target.id}&pageNo=1&pageSize=8`,tokens.warehouse)
const putawayPage = await api('/rd/putaway-task/page?pageNo=1&pageSize=20',tokens.warehouse)
const putaway = putawayPage.list.find(t=>before.some(l=>l.id===t.plannedLocationId))
const loadingPage = await api('/rd/loading-task/page?pageNo=1&pageSize=20',tokens.warehouse)
const loading = loadingPage.list[0]
assert.ok(putaway&&loading,'Requires existing isolated putaway/loading tasks, no new map test stock is invented')
assert.ok(original.list.every(l=>l.locationId===target.id))
assert.notEqual((await request('/rd/stock-lot/page?locationId=-1&pageNo=1&pageSize=8',tokens.warehouse)).code,0)
assert.notEqual((await request('/rd/stock-lot/page?locationId='+target.id,tokens.driver)).code,0)
const requireFrontend = createRequire(path.join(root,'frontend/package.json'))
const {chromium} = process.env.RD_BROWSER_MODULES ? requireFrontend(path.join(process.env.RD_BROWSER_MODULES,'playwright')) : requireFrontend('playwright')
const browser = await chromium.launch({headless:true,channel:process.env.RD_BROWSER_CHANNEL})
const output=path.join(root,'temp/spatial-map-verification');await fs.mkdir(output,{recursive:true})
const errors=[],screens=[],externalResources=[];let writes=0
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000}})
  const page=await context.newPage()
  const clearTooltips=async()=>{
    await page.mouse.move(0,0)
    await page.waitForFunction(()=>![...document.querySelectorAll('.el-popper.is-dark')].some(el=>getComputedStyle(el).display!=='none'&&getComputedStyle(el).visibility!=='hidden'&&el.getBoundingClientRect().width>0))
  }
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>{if(new URL(r.url()).origin!==new URL(baseUrl).origin)externalResources.push(r.url())})
  page.on('request',r=>{if(!['GET','HEAD'].includes(r.method())&&!r.url().includes('/system/auth/')&&!r.url().includes('/system/tenant/'))writes++})
  await page.goto(baseUrl+'/login',{waitUntil:'networkidle'})
  await page.getByPlaceholder('账号',{exact:true}).fill(accounts.warehouse.username)
  await page.getByPlaceholder('密码',{exact:true}).fill(accounts.warehouse.password)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.waitForURL(u=>!u.pathname.includes('/login'))
  await page.goto(baseUrl+'/rd/stock/putaway',{waitUntil:'networkidle'})
  await page.getByRole('region',{name:'库位空间视图',exact:true}).waitFor()
  await page.waitForFunction(()=>document.querySelectorAll('.map-surface .leaflet-overlay-pane path').length>0)
  const region=page.getByRole('region',{name:'库位空间视图',exact:true})
  assert.ok((await region.locator('.leaflet-overlay-pane path').count())>0)
  const geometry=await region.locator('.map-surface').evaluate(el=>({w:el.clientWidth,h:el.clientHeight}))
  assert.ok(geometry.w>200&&geometry.h>=300)
  await region.getByRole('button',{name:'放大库位图',exact:true}).click()
  await region.getByRole('button',{name:'缩小库位图',exact:true}).click()
  await region.getByRole('button',{name:'适配库区',exact:true}).click()
  const surface=region.locator('.map-surface')
  const transform=await surface.locator('.leaflet-map-pane').getAttribute('style')
  const area=await surface.boundingBox()
  await page.mouse.move(area.x+12,area.y+12)
  await page.mouse.down()
  await page.mouse.move(area.x+62,area.y+42,{steps:8})
  await page.mouse.up()
  assert.notEqual(await surface.locator('.leaflet-map-pane').getAttribute('style'),transform,'pan is an actual Leaflet viewport interaction')
  await region.getByRole('button',{name:'适配库区',exact:true}).click()
  for(const width of [1440,390,320]){
    await page.setViewportSize({width,height:width<500?844:1000})
    await region.scrollIntoViewIfNeeded()
    await page.waitForFunction(()=>{const el=document.querySelector('[aria-label="库位空间视图"]');return el&&el.scrollWidth<=el.clientWidth+1},{},{timeout:5000})
    const bounds=await region.evaluate(el=>({w:el.clientWidth,s:el.scrollWidth}))
    assert.ok(bounds.s<=bounds.w+1,`responsive region overflow at ${width}: ${JSON.stringify(bounds)}`)
    await page.waitForFunction(()=>{
      const host=document.querySelector('.map-surface')?.getBoundingClientRect()
      const paths=[...document.querySelectorAll('.map-surface .leaflet-overlay-pane path')]
      return host&&paths.length&&paths.every(p=>{const b=p.getBoundingClientRect();return b.left>=host.left-2&&b.right<=host.right+2&&b.top>=host.top-2&&b.bottom<=host.bottom+2})
    })
    assert.ok(await region.locator('.spatial-bin-label:visible').count(), 'schematic retains readable location codes in each viewport')
    await clearTooltips()
    const name=`warehouse-${width}.png`;await region.screenshot({path:path.join(output,name),animations:'disabled'});screens.push(name)
  }
  await page.setViewportSize({width:1440,height:1000})
  await region.getByText('清单',{exact:true}).click()
  await region.locator('.bin-list button').filter({hasText:target.locationCode}).click()
  await page.getByRole('complementary',{name:`库位资料 ${target.locationCode}`,exact:true}).waitFor()
  await region.getByRole('button',{name:'刷新库位资料',exact:true}).click()
  await page.waitForLoadState('networkidle')
  assert.equal(await region.getByText('该库位库存读取失败，请重新核对',{exact:true}).count(),0)
  await region.getByText('自建示意',{exact:true}).click()
  await page.waitForFunction(()=>document.querySelectorAll('.map-surface .leaflet-overlay-pane path').length>0)
  await region.getByRole('button',{name:'放大库位图',exact:true}).click()
  await region.locator('.spatial-bin-label').first().click()
  await page.waitForLoadState('networkidle')
  await region.getByRole('button',{name:'适配库区',exact:true}).click()
  await clearTooltips()
  await region.screenshot({path:path.join(output,'warehouse-details.png'),animations:'disabled'});screens.push('warehouse-details.png')
  await region.getByText('已登记行列',{exact:true}).click()
  await page.waitForLoadState('networkidle')
  await region.getByText('自建示意',{exact:true}).click()
  await page.getByRole('tab',{name:'上架任务',exact:true}).click()
  await page.locator('.el-form-item:visible').filter({hasText:'任务号'}).getByRole('textbox').fill(putaway.taskNo)
  await page.getByRole('button',{name:'查询',exact:true}).click()
  await page.locator('.el-table__row').filter({hasText:putaway.taskNo}).getByRole('button',{name:'查看',exact:true}).click()
  const putawayDialog=page.getByRole('dialog',{name:'上架任务详情',exact:true})
  await putawayDialog.getByText('任务库位示意',{exact:true}).click()
  const putawayMap=putawayDialog.getByRole('region',{name:'库位空间视图',exact:true})
  await putawayMap.locator('.leaflet-overlay-pane path[stroke-dasharray]').first().waitFor()
  assert.equal(await putawayMap.locator(`.spatial-bin-label[data-location-id="${putaway.plannedLocationId}"]`).count(),1)
  await putawayMap.screenshot({path:path.join(output,'putaway-task-map.png'),animations:'disabled'});screens.push('putaway-task-map.png')
  await page.goto(baseUrl+'/rd/stock/loading',{waitUntil:'networkidle'})
  await page.getByRole('tab',{name:'装车任务',exact:true}).click()
  await page.locator('.el-form-item:visible').filter({hasText:'任务号'}).getByRole('textbox').fill(loading.taskNo)
  await page.getByRole('button',{name:'查询',exact:true}).click()
  await page.locator('.el-table__row').filter({hasText:loading.taskNo}).getByRole('button',{name:'详情',exact:true}).click()
  const loadingDialog=page.getByRole('dialog',{name:'装车任务详情',exact:true})
  await loadingDialog.getByText('整车任务库位示意',{exact:true}).click()
  const loadingMap=loadingDialog.getByRole('region',{name:'库位空间视图',exact:true})
  await loadingMap.locator('.leaflet-overlay-pane path[stroke-dasharray]').first().waitFor()
  await loadingMap.screenshot({path:path.join(output,'loading-task-map.png'),animations:'disabled'});screens.push('loading-task-map.png')
  assert.equal(writes,0,'viewing/zooming/selecting must not write warehouse business state')
  assert.deepEqual(await api('/rd/putaway-task/location-map',tokens.warehouse),before)
  assert.deepEqual(await api(`/rd/stock-lot/page?locationId=${target.id}&pageNo=1&pageSize=8`,tokens.warehouse),original)
  const otherOrigins=await page.evaluate(()=>performance.getEntriesByType('resource').map(e=>new URL(e.name)).filter(u=>u.origin!==location.origin).map(u=>u.href))
  assert.deepEqual(otherOrigins,[],'self-hosted map must not request remote tiles, scripts or images')
  assert.deepEqual(externalResources,[],'all map and task page navigations stay self-hosted')
  assert.deepEqual(errors,[])
  await context.close()
  const report={marker:'自建示意和本地真实接口验证，非现场布局',locations:before.length,screens,errors,writes,unchangedInventory:true,remoteResources:otherOrigins,taskHighlights:{putaway:putaway.id,loading:loading.id},panChecked:true}
  await fs.writeFile(path.join(output,'result.json'),JSON.stringify(report,null,2))
  console.log(JSON.stringify(report))
}finally{await browser.close()}
