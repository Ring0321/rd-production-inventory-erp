const readPixels=async canvas=>canvas.evaluate(element=>{
  const gl=element.getContext('webgl2')
  if(!gl||gl.isContextLost())throw Error('No active WebGL2 canvas')
  const width=element.width,height=element.height,data=new Uint8Array(width*height*4)
  gl.readPixels(0,0,width,height,gl.RGBA,gl.UNSIGNED_BYTE,data)
  let contrast=0,opaque=0,hash=2166136261
  for(let i=0;i<data.length;i+=4){
    if(data[i+3]>0)opaque++
    if(Math.max(data[i],data[i+1],data[i+2])-Math.min(data[i],data[i+1],data[i+2])>15||Math.min(data[i],data[i+1],data[i+2])<190)contrast++
    if(i%64===0)hash=Math.imul(hash^data[i]^data[i+1]^data[i+2],16777619)>>>0
  }
  return {width,height,contrast,opaque,hash,renderer:gl.getParameter(gl.RENDERER)}
})
